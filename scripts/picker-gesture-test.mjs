import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../electron/main.ts',import.meta.url),'utf8');
const fn=source.slice(source.indexOf('function pickerMessage('),source.indexOf('let quitting'));
const calls=[];
const context={pickerOpen:true,pickerOpener:'swipe-left',closePicker:(select=false)=>calls.push(select),openPicker:()=>{},Math};
vm.createContext(context);
vm.runInContext(ts.transpile(fn),context);
for(const motion of ['tap-index','tap-middle','swipe-right','double-tap-middle'])context.pickerMessage({kind:'motion',motion});
assert.deepEqual(calls,[]);
context.pickerMessage({kind:'motion',motion:'swipe-left'});
assert.deepEqual(calls,[false]);
context.pickerMessage({kind:'motion',motion:'double-tap-index'});
assert.deepEqual(calls,[false,true]);
context.pickerOpener='combo-custom';
context.pickerMessage({kind:'motion',motion:'combo-custom'});
assert.deepEqual(calls,[false,true,false]);
context.pickerOpen=false;
context.pickerMessage({kind:'motion',motion:'combo-custom'});
assert.equal(calls.length,3);
console.log('Picker: opener repetition cancels, index double tap selects, single taps do nothing, combos cancel.');
