import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {chromium} from 'playwright-core';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(()=>{
 const listeners=new Set();window.commands=[];
 window.emitModel=message=>listeners.forEach(callback=>callback(message));
 window.band={send:command=>{window.commands.push(command);if(command.action==='model_status')queueMicrotask(()=>window.emitModel({kind:'model_status',model:'handwriting',installed:false,phase:'idle',message:'Not installed'}));},onMessage:callback=>{listeners.add(callback);return()=>listeners.delete(callback);}};
});
await page.goto(process.env.PREVIEW_URL||'http://127.0.0.1:5190');
await page.getByRole('button',{name:'Device settings',exact:true}).click();
await page.getByRole('button',{name:/Open device test/}).click();
await page.getByRole('tab',{name:'Model experiments'}).click();
await page.getByRole('button',{name:/Handwriting Trace letters/}).click();
// Native handwriting is the default and requires no download.
await page.evaluate(()=>window.emitModel({kind:'state',state:'connected'}));
await page.getByRole('button',{name:'Start handwriting',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.at(-1).action==='native_handwriting_start'));
await page.evaluate(()=>window.emitModel({kind:'native_handwriting',phase:'listening',message:'Write a word',verified:false,text:'hello',samples:24,gaps:0,raw:'hello'}));
await page.getByLabel('Native decoded handwriting').filter({hasText:'hello'}).waitFor();
await page.getByRole('button',{name:'Clear text',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.at(-1).action==='native_handwriting_clear'));
await page.getByRole('button',{name:'Stop',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.at(-1).action==='native_handwriting_stop'));
await page.evaluate(()=>window.emitModel({kind:'native_handwriting',phase:'idle',message:'Previous settings verified',verified:true,text:'hello',samples:24,gaps:0}));
await page.getByText('Previous settings verified',{exact:true}).waitFor();
await page.screenshot({path:'docs/model-native-handwriting.png',fullPage:false});
for(const width of [768,390]){
 await page.setViewportSize({width,height:1000});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
}
await page.setViewportSize({width:1440,height:1000});
await page.getByRole('button',{name:'Use the older research checkpoint instead',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.some(command=>command.action==='native_handwriting_stop')));
await page.getByRole('button',{name:'Install model',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.some(command=>command.action==='model_install'&&command.model==='handwriting')));
await page.evaluate(()=>window.emitModel({kind:'model_status',model:'handwriting',installed:false,phase:'installing',message:'Downloading official weights'}));
await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Install model')?.disabled);
await page.getByRole('button',{name:'Cancel installation'}).click();
assert.ok(await page.evaluate(()=>window.commands.at(-1).action==='model_cancel'));
await page.evaluate(()=>{window.emitModel({kind:'model_status',model:'handwriting',installed:true,phase:'ready',message:'Installed and verified on CPU'});window.emitModel({kind:'state',state:'connected'});});
await page.getByRole('button',{name:'Record EMG',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.at(-1).action==='model_capture_start'));
await page.evaluate(()=>window.emitModel({kind:'model_status',model:'handwriting',installed:true,phase:'capturing',message:'Recording',samples:8192}));
await page.getByRole('button',{name:'Finish recording'}).click();
await page.evaluate(()=>window.emitModel({kind:'model_status',model:'handwriting',installed:true,phase:'captured',message:'Recorded 4 seconds',samples:8192}));
await page.getByLabel('Reference text').fill('hello');
await page.getByLabel('Channel mapping').selectOption('interpolate');
await page.getByRole('button',{name:'Run model',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.at(-1).mapping==='interpolate'));
await page.evaluate(()=>window.emitModel({kind:'model_result',model:'handwriting',result:{text:'hello',frames:40,seconds:4,mapping:'repeat',experimental:true,calibration:'unverified'}}));
await page.getByLabel('Decoded handwriting').filter({hasText:'hello'}).waitFor();
assert.equal(await page.getByLabel('Decoded handwriting').textContent(),'hello');
assert.match(await page.locator('.model-score').textContent(),/0%/);
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'docs/model-handwriting.png',fullPage:true});
await page.getByRole('button',{name:'All model experiments'}).click();
await page.getByRole('button',{name:/Hand pose Move your fingers/}).click();
await page.evaluate(landmarks=>{window.emitModel({kind:'model_status',model:'pose',installed:true,phase:'ready',message:'Inference complete',samples:8192});window.emitModel({kind:'model_result',model:'pose',result:{landmarks,angles:[Array(20).fill(0),Array(20).fill(1)],frames:2,seconds:4,mapping:'interpolate',experimental:true,calibration:'unverified'}});},JSON.parse(readFileSync('tests/fixtures/pose-hand.json','utf8')));
await page.waitForFunction(()=>document.querySelectorAll('.pose-joint').length===20);
assert.equal(await page.locator('.pose-joint').count(),20);
const openHand=await page.locator('.pose-hand-model .pose-bone').first().getAttribute('d');
await page.getByLabel('Pose frame').fill('1');
await page.waitForFunction(previous=>document.querySelector('.pose-bone')?.getAttribute('d')!==previous,openHand);
const oblique=await page.locator('.pose-bone').first().getAttribute('d');
await page.getByRole('button',{name:'Side',exact:true}).click();
assert.notEqual(await page.locator('.pose-bone').first().getAttribute('d'),oblique);
await page.getByRole('button',{name:'Oblique',exact:true}).click();
await page.getByRole('button',{name:'Play pose playback'}).click();
await page.getByRole('button',{name:'Pause pose playback'}).click();
assert.match(await page.locator('.pose-joint strong').first().textContent(),/57.3/);
await page.getByLabel('Pose frame').fill('0');
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'docs/model-pose.png',fullPage:true});
if(process.env.MODEL_LAYOUT_SNAPSHOT)writeFileSync(process.env.MODEL_LAYOUT_SNAPSHOT,(await page.content()).replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').replace('<head>','<head><base href="http://127.0.0.1:5190/">'));
for(const width of [768,390]){
 await page.setViewportSize({width,height:1000});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:`docs/model-pose-${width}.png`,fullPage:false});
 await page.locator('.model-output').scrollIntoViewIfNeeded();
 await page.screenshot({path:`docs/model-pose-${width}-output.png`,fullPage:false});
}
await page.getByRole('tab',{name:'Live signals',exact:true}).click();
assert.ok(await page.evaluate(()=>window.commands.some(command=>command.action==='model_leave')));
assert.deepEqual(errors,[]);
await browser.close();
console.log('Model test pages: native handwriting start/stop/clear/text and responsive layout, install/cancel, record/run, mapping, decoded text/CER, 20 joint angles, articulated hand geometry, camera views, playback, navigation and responsive layout passed.');
